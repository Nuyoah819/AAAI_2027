def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run the unified APTC SECT-CoCo-E2E pipeline on 9 datasets.")
    parser.add_argument("--datasets", default=",".join(DATASETS))
    parser.add_argument("--data-root", default=str(DATA_ROOT))
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--epochs", type=int, default=0, help="Override epochs for smoke tests.")
    parser.add_argument("--device", default="")
    parser.add_argument("--log-level", default="INFO")
    parser.add_argument("--variant", default="v8g_full", choices=sorted(EXPERIMENT_VARIANTS))
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    logging.basicConfig(level=getattr(logging, args.log_level.upper(), logging.INFO), format="%(asctime)s | %(levelname)s | %(message)s")
    results_dir = PROJECT_ROOT / "results"
    results_dir.mkdir(exist_ok=True)
    variant = EXPERIMENT_VARIANTS[args.variant]
    csv_path = results_dir / f"{variant['output_stem']}.csv"
    jsonl_path = results_dir / f"{variant['output_stem']}_diagnostics.jsonl"
    datasets = [d.strip().lower() for d in args.datasets.split(",") if d.strip()]
    summary: dict[str, dict] = {}

    for dataset_name in datasets:
        logging.info("[%s] loading", dataset_name)
        try:
            dataset = load_dataset(dataset_name, args.data_root)
            dataset_cfg = DATASET_CONFIGS.get(dataset_name, {})
            tfidf = bool(dataset_cfg.get("tfidf", True))
            features = preprocess_features(dataset.features, tfidf=tfidf, norm="l2", dtype="float32")
        except Exception:
            err = traceback.format_exc()
            _append_csv(csv_path, {"dataset": dataset_name, "candidate": "load", "status": "error", "error": err})
            logging.error("[%s] load failed\n%s", dataset_name, err)
            continue

        cfg_dict = unified_config(dataset_name, args.variant)
        if args.epochs > 0:
            cfg_dict["epochs"] = args.epochs
            cfg_dict["pretrain_epochs"] = min(cfg_dict.get("pretrain_epochs", 10), max(0, args.epochs // 4))
        if args.device:
            cfg_dict["device"] = args.device

        cfg = E2ESECTCoCoConfig.from_dict(cfg_dict, seed=args.seed)
        logging.info("[%s][%s] running unified APTC", dataset_name, cfg.name)
        start = time.perf_counter()
        try:
            estimator = E2ESECTCoCo(dataset.n_clusters, cfg)
            estimator._true_labels_ = dataset.labels
            graph_adj = dataset.directed_adj if dataset.directed_adj is not None else dataset.adj
            pred = estimator.fit_predict(dataset.adj, features, graph_features_adj=graph_adj, true_labels=dataset.labels)
            metrics = evaluate_clustering(dataset.labels, pred)
            target = TARGETS.get(dataset_name, {})
            row = {
                "dataset": dataset_name,
                "candidate": cfg.name,
                "status": "ok",
                **metrics,
                "target_acc": target.get("acc", ""),
                "target_nmi": target.get("nmi", ""),
                "target_ari": target.get("ari", ""),
                "delta_acc": metrics["acc"] - target.get("acc", 0.0),
                "delta_nmi": metrics["nmi"] - target.get("nmi", 0.0),
                "delta_ari": metrics["ari"] - target.get("ari", 0.0),
                "runtime_sec": round(time.perf_counter() - start, 3),
                "error": "",
            }
            diag = dict(estimator.diagnostics_)
            diag.update(row)
            _append_csv(csv_path, row)
            _append_jsonl(jsonl_path, diag)
            summary[dataset_name] = row
            logging.info(
                "[%s] ACC=%.4f NMI=%.4f ARI=%.4f dACC=%.4f dNMI=%.4f dARI=%.4f",
                dataset_name,
                row["acc"],
                row["nmi"],
                row["ari"],
                row["delta_acc"],
                row["delta_nmi"],
                row["delta_ari"],
            )
        except Exception:
            err = traceback.format_exc()
            row = {"dataset": dataset_name, "candidate": cfg.name, "status": "error", "error": err}
            _append_csv(csv_path, row)
            summary[dataset_name] = row
            logging.error("[%s][%s] failed\n%s", dataset_name, cfg.name, err)

    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


def unified_config(dataset: str, variant: str = "v8g_full") -> dict:
    merged = dict(BASE_CONFIG)
    dataset_cfg = {k: v for k, v in DATASET_CONFIGS.get(dataset, {}).items() if k not in REMOVED_BACKEND_KEYS}
    merged.update(dataset_cfg)
    merged.update(UNIFIED_APTC_DEFAULTS)
    merged.update(EXPERIMENT_VARIANTS[variant]["overrides"])
    merged["name"] = f"sect_coco_e2e_unified_aptc_{dataset}"
    return merged


def _append_csv(path: Path, row: dict) -> None:
    fields = [
        "dataset",
        "candidate",
        "status",
        "acc",
        "nmi",
        "ari",
        "f1",
        "target_acc",
        "target_nmi",
        "target_ari",
        "delta_acc",
        "delta_nmi",
        "delta_ari",
        "runtime_sec",
        "error",
    ]
    write_header = not path.exists() or path.stat().st_size == 0
    with path.open("a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        if write_header:
            writer.writeheader()
        writer.writerow({field: row.get(field, "") for field in fields})


def _append_jsonl(path: Path, payload: dict) -> None:
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(payload, ensure_ascii=False, sort_keys=True) + "\n")


